#!/usr/bin/env python3
"""
Write ../tests/position_vectors.js: for a set of phone GPS fixes, the exact Position
bytes the Meshtastic iPhone app would build, made here with the real protobuf library
by following its Swift source line by line:

  AccessoryManager+Position.swift   getPositionFromPhoneGPS
  Position+WireUnits.swift          setSpeedTrackAndHae
  LocationsHandler.swift            satsInView

tests.html then checks that tracker.js produces the same bytes. (The packet around
them is a broadcast with its own id, which tests.html checks field by field.)

    python tools/make_position_vectors.py
"""
import json
import math
import os

from meshtastic.protobuf import mesh_pb2

MY_NODE = 0x0A11CE01
NOW_MS = 1794700000123          # "Date()" at the moment of sending


def swift_rounded(x):
    """Swift's .rounded(): to nearest, ties away from zero."""
    return math.floor(x + 0.5) if x >= 0 else math.ceil(x - 0.5)


def sats_in_view(h, v):
    sats = 1
    if v > 0:
        sats = 4
        if 0 <= h <= 5:
            sats = 12
        elif 6 <= h <= 15:
            sats = 10
        elif 16 <= h <= 30:
            sats = 9
        elif 31 <= h <= 45:
            sats = 7
        elif 46 <= h <= 60:
            sats = 5
    elif v < 0 and 60 <= h <= 300:
        sats = 3
    elif v < 0 and h > 300:
        sats = 2
    return sats


def position(fix):
    """getPositionFromPhoneGPS(destNum:, fixedPosition: false). A web fix has no
    ellipsoidal altitude, so altitude_hae stays unset (Swift leaves it unset when invalid)."""
    if fix["latitude"] == 0 and fix["longitude"] == 0:
        return None
    p = mesh_pb2.Position()
    p.latitude_i = int(fix["latitude"] * 1e7)            # Int32(Double) truncates toward zero
    p.longitude_i = int(fix["longitude"] * 1e7)
    p.time = NOW_MS // 1000
    p.timestamp = fix["timestamp"] // 1000
    p.altitude = int(fix["altitude"] if fix["altitude"] is not None else 0)
    v = fix["altitudeAccuracy"] if fix["altitudeAccuracy"] is not None else -1
    p.sats_in_view = sats_in_view(fix["accuracy"], v)
    speed = fix["speed"]
    if speed is not None and speed >= 0:
        p.ground_speed = swift_rounded(speed * 3.6)
    course = fix["heading"]
    if course is not None and course >= 0:
        p.ground_track = swift_rounded(course * 100000) % 36000000
    p.location_source = mesh_pb2.Position.LocSource.LOC_EXTERNAL
    return p


def fix(lat, lon, alt, acc, vacc, heading, speed, age_ms=800):
    return {"latitude": lat, "longitude": lon, "altitude": alt, "accuracy": acc, "altitudeAccuracy": vacc,
            "heading": heading, "speed": speed, "timestamp": NOW_MS - age_ms}


FIXES = [
    ("moving boat, good fix", fix(27.9506543, -82.4567891, 3.7, 4.2, 6.0, 271.34567, 6.1728)),
    ("standing still: speed 0 is a reading, no course", fix(27.95, -82.54, 6.0, 12.0, 15.0, None, 0.0)),
    ("no speed, no course, no altitude", fix(27.975999, -82.501001, None, 35.0, None, None, None)),
    ("southern / eastern hemisphere, negative altitude", fix(-33.8688123, 151.2093456, -2.9, 5.5, 3.0, 359.999996, 12.5)),
    ("poor fix, no vertical accuracy", fix(40.7127753, -74.0059728, 10.0, 120.0, None, 90.0, 1.0)),
    ("very poor fix", fix(51.5073509, -0.1277583, 20.0, 800.0, None, 0.0, 0.4)),
    ("accuracy in a gap between bands (5.5 m)", fix(27.1, -82.2, 1.0, 5.5, 4.0, 180.0, 2.0)),
    ("accuracy 46-60 m", fix(27.2, -82.3, 2.0, 50.0, 30.0, 45.5, 30.0)),
    ("old fix, phone not moving", fix(27.3, -82.4, 0.0, 8.0, 9.0, None, None, age_ms=95000)),
    ("0,0 is never sent", fix(0.0, 0.0, 0.0, 5.0, 5.0, None, None)),
]

out = []
for name, f in FIXES:
    p = position(f)
    out.append({"name": name, "fix": f, "position_hex": p.SerializeToString().hex() if p else None})

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "position_vectors.js")
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by tools/make_position_vectors.py. Do not edit.\n")
    fh.write("window.POSITION_VECTORS=" + json.dumps({"my_node": MY_NODE, "now_ms": NOW_MS, "cases": out},
                                                    separators=(",", ":")) + ";\n")
print(len(out), "cases ->", os.path.normpath(path))
